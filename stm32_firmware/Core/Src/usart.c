/**
  * @brief  printf 重定向：把所有 printf 输出到 USART1。
  *         没有这个函数，printf 会走 ARM 库默认的 semihosting(半主机)，
  *         没有连接调试器时 MCU 会卡死/无输出，这是串口没反应的重要原因。
  */
int fputc(int ch, FILE *f)
{
    (void)f;
    HAL_UART_Transmit(&huart1, (uint8_t *)&ch, 1, 100);
    return ch;
}

/**
  * @brief  格式化串口打印助手（等价于 printf，但显式走 HAL 发送，不依赖重定向）
  * @param  fmt: 格式化字符串（支持 %d %f %s 等）
  */
void uart_printf(const char *fmt, ...)
{
    char buf[128];
    va_list args;
    va_start(args, fmt);
    vsnprintf(buf, sizeof(buf), fmt, args);
    va_end(args);
    HAL_UART_Transmit(&huart1, (uint8_t *)buf, strlen(buf), 100);
}

