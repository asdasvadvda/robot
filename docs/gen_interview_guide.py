def set_run(run, ea='宋体', size=11, bold=False, color=None):
    run.font.name = 'Consolas' if ea == 'code' else 'Times New Roman'
    run._element.rPr.rFonts.set(qn('w:eastAsia'), '黑体' if ea == 'code' else ea)
    run.font.size = Pt(size)
    run.font.bold = bold
    if color:
        run.font.color.rgb = color


_INLINE = re.compile(r'(\*\*.*?\*\*|`[^`]*`)')


def _fill(p, text, size=11, bold=False, space_after=6):
    for seg in _INLINE.split(text):
        if not seg:
            continue
        if seg.startswith('**') and seg.endswith('**'):
            add_run = p.add_run(seg[2:-2])
            set_run(add_run, size=size, bold=True)
        elif seg.startswith('`') and seg.endswith('`'):
            add_run = p.add_run(seg[1:-1])
            set_run(add_run, ea='code', size=size - 0.5)
        else:
            add_run = p.add_run(seg)
            set_run(add_run, size=size, bold=bold)
    p.paragraph_format.line_spacing = 1.3
    p.paragraph_format.space_after = Pt(space_after)
    return p


def h1(text):
    doc.add_heading(text, level=1)


def h2(text):
    doc.add_heading(text, level=2)


def h3(text):
    doc.add_heading(text, level=3)


def p(text, size=11, bold=False, align=None, space_after=6):
    para = doc.add_paragraph()
    _fill(para, text, size=size, bold=bold, space_after=space_after)
    if align is not None:
        para.alignment = align
    return para


def li(text, size=11):
    para = doc.add_paragraph(style='List Bullet')
    _fill(para, text, size=size, space_after=3)
    return para


def note(text):
    para = doc.add_paragraph()
    para.paragraph_format.left_indent = Cm(0.6)
    para.paragraph_format.line_spacing = 1.3
    para.paragraph_format.space_after = Pt(6)
    r = para.add_run('【记】')
    set_run(r, ea='黑体', size=10.5, bold=True, color=RGBColor(0x1F, 0x4E, 0x79))
    _fill(para, text, size=10.5)
    # 统一字号,保留原有的加粗状态
    for seg in para.runs:
        if seg.text and seg.text.startswith('【记】'):
            continue
        set_run(seg, size=10.5, bold=seg.font.bold)
    return para


def code_block(text):
    for line in text.strip('\n').split('\n'):
        para = doc.add_paragraph()
        r = para.add_run(line)
        set_run(r, ea='code', size=9.5)
        para.paragraph_format.line_spacing = 1.15
        para.paragraph_format.space_after = Pt(0)
        para.paragraph_format.left_indent = Cm(0.5)
        pPr = para._p.get_or_add_pPr()
        shd = OxmlElement('w:shd')
        shd.set(qn('w:val'), 'clear')
        shd.set(qn('w:fill'), 'F2F2F2')
        pPr.append(shd)
    p('').paragraph_format.space_after = Pt(2)


def shade(cell, color='D9E2F3'):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear')
    shd.set(qn('w:fill'), color)
    tcPr.append(shd)


def table(headers, rows, widths=None, font_size=10):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = 'Table Grid'
    t.autofit = False
    for i, h in enumerate(headers):
        cell = t.rows[0].cells[i]
        cell.paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = cell.paragraphs[0].add_run(h)
        set_run(r, ea='黑体', size=font_size, bold=True)
        shade(cell)
        if widths:
            cell.width = Cm(widths[i])
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            _fill(cells[i].paragraphs[0], str(v), size=font_size, space_after=2)
            if widths:
                cells[i].width = Cm(widths[i])
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t


