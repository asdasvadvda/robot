li('**为什么导航用 Action 不用 Service/Topic?** 导航是长任务(几秒~几分钟),需要:随时取消(车撞人了)、持续反馈(还剩多远)、结果回执(到没到)。Topic 没反馈没回执,Service 不能取消。Action = 三个话题拼起来:goal/cancel(服务)+ feedback/result(话题)。')
li('**ROS2 的 QoS?** 可靠 vs 尽力而为:激光点云、粒子云这些「丢一帧无所谓的流」用 best_effort;控制指令用 reliable。项目里 AMCL 粒子云是 best_effort + nav2_msgs 专用类型,订阅错 QoS 或错类型会「永远收不到」——这是真实踩过的坑。')
li('**为什么容器化?** 环境一致、可复现、宿主机干净。注意:容器内没有 docker 命令,判断是否在容器看 /.dockerenv,别被「which docker 找不到」误导。')

h2('3.2 TF 坐标树(必考)')
code_block('map ──(AMCL)──> odom ──(EKF)──> base_link ──(static)──> laser_frame')
li('**map→odom**:AMCL 广播。含义是「里程计原点在地图里的位置」,即定位修正量——odom 系内部连续,map 系把它整体对齐到地图。')
li('**odom→base_link**:EKF 广播(驱动故意 publish_tf=false)。含义是「车在里程计系里的位姿」,由融合里程计给出。')
li('**base_link→laser_frame**:静态 TF,雷达在车上的安装位置(z=0.13m)。')
p('**为什么 odom→base_link 必须只有一个发布者?** 如果驱动和 EKF 都广播,两个位姿源打架,下游每个时刻看到跳变。原则:**一个坐标系变换只有一个权威源**。这也是 EKF 里『map_frame: map、odom_frame: odom、world_frame: odom』配置的意义——EKF 只维护 odom 系,map 系是 AMCL 的事,职责分离。')

h2('3.3 轮式里程计(小白版)')
li('差分底盘两个轮子各带编码器,测出左右轮转速 vl、vr,则:线速度 v=(vl+vr)/2,角速度 w=(vr-vl)/轮距。把 (v,w) 每秒积分,就得到位姿 (x, y, yaw)。')
li('**为什么里程计会漂?** ① 打滑/滑移:轮子空转,编码器转了很多,车没走那么多;② 轮径误差:胎压/磨损让「转一圈=2πr」不准;③ 航向积分误差会放大位置误差(方向错一点,走得越远偏得越多)。')
li('**里程计的优点**:短期精度高、连续、无跳变——所以它是控制反馈(纠偏、DWB)的首选。')
li('**怎么补救**:和 IMU 融合(角速度互相校验)、激光定位修正(map 系)、标定轮距/轮径。')

h2('3.4 IMU(小白版)')
li('六轴 IMU = 三轴加速度计 + 三轴陀螺仪。加速度计测**比力**(静止时读 +g 而不是 0!);陀螺仪测角速度。')
li('**为什么 IMU 不能自己定航向?** 加速度计可以测出重力方向(roll/pitch),但没有磁力计就**没有任何绝对航向参考**——yaw 只能靠陀螺积分,而陀螺有 bias 和噪声,积分误差随时间无界增长。这就是「6 轴 IMU 的 yaw 会漂」的根因。')
li('**Madgwick 滤波**:把加速度计(慢、绝对)和陀螺(快、积分)互补融合,输出姿态四元数;但 yaw 部分本质上还是陀螺积分。')
li('**陀螺轴与车体轴的坑**:芯片坐标系 ≠ 车体 FLU 坐标系(FLU = 前左上)。本项目实测 STM32 的 gx/gy 与 FLU 不一致(FLU 下 wx=gy, wy=-gx),直接用会把轴向误差带进姿态——这是自研 ESKF 航向发散的根因之一(见第6章)。')
note('背法:加速度计给「天」,陀螺给「转」,没有磁力计就没有「北」——yaw 是浮动的。')

h2('3.5 卡尔曼滤波与 EKF(必考)')
p('**一句话**:卡尔曼滤波 = 模型预测 + 测量修正,用**协方差**表示「我有多不确定」,自动决定模型和测量谁更可信。')
li('预测步:按运动模型把状态推一步(车按 v,w 走),不确定度变大(协方差 P 变大)。')
