h2('3.6 ESKF(自研,差异化亮点)')
p('**误差状态卡尔曼滤波(ESKF)**:估计的不是状态本身,而是「名义状态与真实状态的**误差**」。')
li('为什么用误差状态:① 误差很小 → 线性化误差小 → 比直接 EKF 稳;② 姿态在 SO(3) 流形上,误差是一个三维向量,避开欧拉角的奇异性/万向锁;③ 陀螺 bias 等小量可以在误差状态里被估计出来。')
li('本项目从零实现(学习工程 stage0~6:状态预测、误差传播、观测更新、bias 估计等逐步搭起来),节点 eskf_ros,输入 /odom + /imu.data,输出 /odom_filtered。')
li('**同数据背靠背对比(2026-08-27)**:录一段 168s / 9.5m 带转向回环的实车数据,离线重放——同一份输入分别喂 robot_localization 和自己写的 ESKF,按消息时间戳对齐比较。结果:**ESKF 航向误差均值 42.5°、位置误差均值 68cm,回原点漂移 4.01m vs EKF 的 2.27m**。')
li('**三个根因(这是最有价值的部分)**:① 陀螺 gx/gy 未转 FLU 轴系;② 陀螺 bias 不估计(教学简化)——bias 是 yaw 无界漂移的源头;③ odom 只当位置观测,没用轮式 wz/yaw——轮式角速度无漂移,EKF 正是靠它约束航向。')
li('**下一步(面试开放题现成答案)**:修这三处,同 bag 重放复测;再加磁力计做绝对航向。')
note('这个故事面试官会非常感兴趣:自己实现 → 与工业标准对比 → 数据说话 → 根因定位 → 有修复计划。比「我调好了 Nav2」高一个层次。')

h2('3.7 AMCL 粒子滤波定位(必考)')
li('**粒子滤波白话**:撒 N 个粒子(每个 = 一个「车可能在的位置+朝向」的假设),每步三件事:① 运动模型推每个粒子(加噪声,模拟不确定);② 激光点云和地图匹配,给每个粒子打分(匹配得好的权重高);③ 重采样(权重高的粒子多复制,低的淘汰)。收敛后粒子扎堆 = 定位锁定。')
li('**初值**:初始位姿给得好,粒子从附近收敛(几分钟);给「大协方差」初值 = 粒子撒满全图,车动起来自己收敛(等效全局定位)。')
li('**运动门控(本项目踩过)**:AMCL 默认**车静止时不更新不发布**——移动超过 update_min_d/update_min_a 才干活。后果:车停稳后永远等不到 /amcl_pose。本项目把门控调小(0.25m→0.05m、0.2rad→0.1rad),并给航点记录脚本加了「等 2 秒无 pose 就改读 TF」的兜底。')
li('**绑架问题(本项目踩过)**:粒子已经收敛,此时**手搬车**,激光场景突变,AMCL 会把粒子重采样到错误位置(被「绑架」),之后的定位全部是错的。这是「记录航点期间绝对不许搬车」的技术原因——要么 teleop 开过去,要么停掉导航栈再搬。')
li('**本项目版本缺陷与解法**:Nav2 1.1.13 的 AMCL ① 没有 /global_localization 全局定位服务;② 不认零协方差 /initialpose。解法:发布**大协方差** initialpose(均值=地图探索区中心,协方差盖全图)→ 等效撒满粒子;收敛判定写脚本按粒子加权标准差 <0.2m 判断。')
note('背法:粒子=假设;运动=推;激光=打分;重采样=优胜劣汰;静止=不发布;搬车=绑架。')

h2('3.8 Nav2 导航框架(必考)')
li('**架构**:BT Navigator(行为树,任务级调度:算路径→跟路径→到点判定→失败恢复)→ planner(全局路径)+ controller(局部速度)+ costmap(代价地图)+ velocity_smoother(速度平滑)。全部 lifecycle 管理,启动顺序由 launch 编排。')
li('**NavFn 全局规划白话**:从目标点在地图上做势场扩散(像水面波纹),每个格子记「到目标的最短距离」,规划时从起点沿梯度下降走。走的是全局最优-ish 的路径。')
li('**DWB 局部控制白话**:每 100ms 采样一大把候选速度 (v, w),对每个候选向前模拟一小段轨迹,按「离全局路径近、不碰障碍、速度快」打分,选最好的执行。这就是局部避障:绕开全局路径上突然出现的障碍。')
li('**代价地图**:静态层(加载地图)+ 膨胀层(把障碍周围「膨胀」出一圈不可达/高代价区域,相当于车的安全距离)。所以停点必须离障碍 0.5m 以上,贴墙的目标点 DWB 永远选不出安全轨迹。')
li('**velocity_smoother**:限制速度/加速度突变,不然轮子猛冲;同时它负责把「刹车死区」考虑进规划(见电机死区)。')
li('**到点判定**:goal_checker 每帧检查「离目标 < xy_goal_tolerance 且 角度差 < yaw_goal_tolerance」→ 判到达。这个判定和 DWB 内部容差的配合关系是本项目最精彩的坑(第6章坑1)。')
note('背法:BT 定任务、NavFn 定大方向、DWB 定脚下速度、costmap 画禁区、smoother 管舒适。')

