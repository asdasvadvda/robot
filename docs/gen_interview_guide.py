h2('坑1:到点判定三连锁死(最精彩,必讲)')
li('**现象**:车到了目标点附近,来回微调、原地打转,但系统永不判「到达」,直到超时。')
li('**排查**:先确认定位正常(AMCL 有 pose、tf 对),再确认规划执行正常(cmd_vel 有输出),最后发现三个参数各自都有问题,叠加成死锁。')
li('**根因**:① AMCL 运动门控 0.25m——车在目标点附近微调位移小,定位冻结不更新;② DWB 内部到点容差 0.15 = 外部判定圈 0.15——车在圈外停下只旋转,永远进不了圈;③ 旋转死区——wz=0.15 时轮子实测纹丝不动,朝向永远对不齐。')
li('**修复**:update_min_d 0.25→0.05、update_min_a 0.2→0.1;内部容差 0.15→0.05;min_speed_theta 0.15→0.3。')
li('**结果**:完整巡检 2/2 通过,停点误差 0.12m / 3.3°。')
note('讲法:强调「三个参数单独看都没大问题,叠在一起才死锁」——体现系统思维。')

h2('坑2:键盘遥控和 Nav2 抢 /cmd_vel(轮子冻结)')
li('**现象**:键盘遥控没退出就去跑巡检,车在巡检中轮子突然冻结。')
li('**根因**:键盘的直行纠偏脚本和 Nav2 的控制器同时订阅/发布 /cmd_vel 链路,键盘 idle 时发布旧指令/抢占,把轮子「锁死」。')
li('**修复/规范**:跑导航前必须完全退出键盘;用 `ros2 topic info /cmd_vel -v` 确认发布者只剩 Nav2 相关节点。')
li('**教训**:共享资源(/cmd_vel)的互斥是系统级问题,不是代码 bug——要有操作规范 + 可验证的检查手段。')

h2('坑3:手搬车导致 AMCL 被绑架,航点全废')
li('**现象**:搬车后记录的航点全部不对,巡检乱跑。')
li('**根因**:AMCL 粒子已收敛,搬车时轮子不动、雷达在扫,环境突变被粒子滤波当成「重定位」——粒子重采样到错误位置,定位被绑架;之后一切基于定位的东西全错。')
li('**修复/规范**:定位运行期间绝不搬车,必须用键盘遥控移动;例外是导航栈完全停止时搬车,重启后重设初始位姿。')
li('**结果**:该规范写进了操作手册,之后再没出过同类事故。')

h2('坑4:车停着等不到 /amcl_pose')
li('**现象**:车停到巡检点,跑记录航点脚本,永远等不到第一帧 /amcl_pose。')
li('**根因**:AMCL 运动门控——静止时不更新不发布(Nav2 设计如此,不是故障)。')
li('**修复**:等 2 秒无 pose 就改采 tf map→base_link(等价定位位姿,静止时持续发布)。')
li('**结果**:记录航点流程稳定可用。')

h2('坑5:这个 AMCL 版本不能全局定位')
li('**现象**:换了新地图(无胶带锚定原点),需要自定位但发布 global_localization 服务找不到。')
